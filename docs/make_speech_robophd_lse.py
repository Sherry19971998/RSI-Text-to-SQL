def run(p, text, bold=False, color=None, size=None):
    r = p.add_run(text)
    r.bold = bold
    r.font.name = "PingFang SC"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "PingFang SC")
    if color:
        r.font.color.rgb = RGBColor.from_string(color)
    if size:
        r.font.size = Pt(size)


for kind, text in S:
    p = d.add_paragraph()
    pf = p.paragraph_format
    if kind == "T":
        run(p, text, bold=True, size=17); pf.space_after = Pt(10)
    elif kind == "M":
        run(p, text, color="666666", size=10); pf.space_after = Pt(14)
    elif kind == "H":
        run(p, text, bold=True, color="C0262D", size=14); pf.space_before = Pt(16); pf.keep_with_next = True
    elif kind == "C":
        run(p, text, color="2F6DB5", size=10.5); pf.keep_with_next = True; pf.space_after = Pt(2)
    elif kind == "Q":
        run(p, text, bold=True); pf.keep_with_next = True; pf.space_after = Pt(2)
    else:
        for i, part in enumerate(re.split(r"\*\*", text)):
            if part:
                run(p, part, bold=(i % 2 == 1))
        if kind == "P":
            pf.first_line_indent = Pt(23)

