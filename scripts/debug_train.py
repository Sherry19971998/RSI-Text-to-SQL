"""Diagnose broken LoRA training (NaN grads / huge loss). Three checks, from the bottom up:
  A. base model, no LoRA, one example at a time: loss should be low (~0.1-0.5) because the
     trajectories were generated by this same model
  B. the same examples padded into one batch: loss should match A
  C. a few real Trainer steps with logging every step: loss / grad_norm should stay finite

python scripts/debug_train.py --config configs/phase0.yaml [--scan | --scan-only]
"""
import argparse
import math
import shutil
import tempfile

from rsi.train import build_example, train_lora
from rsi.utils import load_config, read_json, read_jsonl


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/phase0.yaml")
    ap.add_argument("--n", type=int, default=6)
    ap.add_argument("--scan", action="store_true", help="[D] check every training example")
    ap.add_argument("--scan-only", action="store_true", help="stop after [D]")
    args = ap.parse_args()
    args.scan = args.scan or args.scan_only
    cfg = load_config(args.config)

    import torch
    import transformers
    from transformers import AutoModelForCausalLM, AutoTokenizer

    batch = read_json(f"{cfg['run_dir']}/batches.json")[0]
    trajs = {t["traj_id"]: t for t in read_jsonl(cfg["pool_rollouts"])}
    convs = [trajs[i]["messages"] for i in batch["traj_ids"]]

    tok = AutoTokenizer.from_pretrained(cfg["model"])
    feats = [f for f in (build_example(tok, m, cfg["train"]["max_len"]) for m in convs) if f][:args.n]
    print(f"transformers {transformers.__version__}, pad_token={tok.pad_token!r} id={tok.pad_token_id}")
    f0 = feats[0]
    lab = [t for t in f0["labels"] if t != -100]
    print(f"example 0: {len(f0['input_ids'])} tokens, {len(lab)} label tokens")
    print(f"  label text (start): {tok.decode(lab)[:150]!r}")

    model = AutoModelForCausalLM.from_pretrained(cfg["model"], dtype=torch.bfloat16,
                                                 attn_implementation="sdpa").cuda().eval()
    print(f"model dtype {model.dtype}, lm_head tied: {model.config.tie_word_embeddings}")

    print("\n[A] per-example loss, base model:")
    single = []
    with torch.no_grad():
        for f in feats:
            ids = torch.tensor([f["input_ids"]]).cuda()
            out = model(input_ids=ids, labels=torch.tensor([f["labels"]]).cuda())
            single.append(out.loss.item())
            print(f"  loss={out.loss.item():.4f}")

    print("\n[B] same examples, right-padded batch:")
    L = max(len(f["input_ids"]) for f in feats)
    pad = tok.pad_token_id
    ids = torch.tensor([f["input_ids"] + [pad] * (L - len(f["input_ids"])) for f in feats]).cuda()
    labs = torch.tensor([f["labels"] + [-100] * (L - len(f["labels"])) for f in feats]).cuda()
    att = torch.tensor([[1] * len(f["input_ids"]) + [0] * (L - len(f["input_ids"])) for f in feats]).cuda()
    with torch.no_grad():
        out = model(input_ids=ids, attention_mask=att, labels=labs)
    print(f"  batch loss={out.loss.item():.4f}  (mean of A: {sum(single) / len(single):.4f})")

    if args.scan:
        print("\n[D] scan every example of every batch for non-finite / extreme loss:")
        bad = []
        for b in read_json(f"{cfg['run_dir']}/batches.json"):
            for tid in b["traj_ids"]:
                f = build_example(tok, trajs[tid]["messages"], cfg["train"]["max_len"])
                if f is None:
                    continue
                with torch.no_grad():
                    loss = model(input_ids=torch.tensor([f["input_ids"]]).cuda(),
                                 labels=torch.tensor([f["labels"]]).cuda()).loss.item()
                if not math.isfinite(loss) or loss > 3:
                    bad.append((b["batch_id"], tid, loss, len(f["input_ids"])))
                    print(f"  {b['batch_id']} {tid}: loss={loss} tokens={len(f['input_ids'])}")
        print(f"  {len(bad)} suspicious examples")
        if bad:
            t = trajs[bad[0][1]]
            print(f"  first one, last assistant turn (tail):\n{t['messages'][-1]['content'][-400:]!r}")
        if args.scan_only:
            return
    del model
    torch.cuda.empty_cache()

    print("\n[C] 4 Trainer steps, logging every step:")
    tcfg = {**cfg["train"], "epochs": 1, "logging_steps": 1}
    n = 4 * tcfg["per_device_batch"] * tcfg["grad_accum"]
    out_dir = tempfile.mkdtemp(prefix="dbg_lora_", dir=".")
    try:
        meta = train_lora(cfg["model"], convs[:n], out_dir, 0, tcfg)
        print(f"  train_loss={meta['train_loss']:.4f} finite={math.isfinite(meta['train_loss'])}")
    finally:
        shutil.rmtree(out_dir, ignore_errors=True)


if __name__ == "__main__":
    main()
